#Графік 2. Planned contrast
дані_графік_контрасту <- дані_чисті %>%
  filter(умови_освітлення %in% c(
    "Денне світло",
    "Темрява, освітлення відсутнє"
  )) %>%
  group_by(умови_освітлення) %>%
  summarise(
    n = n(),
    легкі_ДТП = sum(severe == 0),
    тяжкі_ДТП = sum(severe == 1),
    частка_тяжких = тяжкі_ДТП / n,
    ci_lower = довірчий_інтервал_частки(тяжкі_ДТП, n)["lower"],
    ci_upper = довірчий_інтервал_частки(тяжкі_ДТП, n)["upper"],
    .groups = "drop"
  ) %>%
  mutate(
    частка_тяжких_відсотки = частка_тяжких * 100,
    ci_lower_відсотки = ci_lower * 100,
    ci_upper_відсотки = ci_upper * 100,
    умови_освітлення = factor(
      умови_освітлення,
      levels = c("Денне світло", "Темрява, освітлення відсутнє")
    )
  )

