#Wald-довірчий інтервал для частки
довірчий_інтервал_частки <- function(x, n, alpha = 0.05) {
  p_hat <- x / n
  z <- qnorm(1 - alpha / 2)
  se <- sqrt(p_hat * (1 - p_hat) / n)
  
  c(
    lower = p_hat - z * se,
    upper = p_hat + z * se
  )
}

#Очікувані частоти для χ²-тесту
очікувані_частоти <- function(таблиця) {
  суми_рядків <- rowSums(таблиця)
  суми_стовпців <- colSums(таблиця)
  загальна_сума <- sum(таблиця)
  
  outer(суми_рядків, суми_стовпців) / загальна_сума
}

#Ручний χ²-тест незалежності
хи_квадрат_тест <- function(таблиця) {
  очікувані <- очікувані_частоти(таблиця)
  статистика <- sum((таблиця - очікувані)^2 / очікувані)
  ступені_вільності <- (nrow(таблиця) - 1) * (ncol(таблиця) - 1)
  p_value <- pchisq(статистика, df = ступені_вільності, lower.tail = FALSE)
  
  list(
    statistic = статистика,
    df = ступені_вільності,
    p_value = p_value
  )
}

#Cramer's V
cramers_v <- function(таблиця) {
  хи2 <- хи_квадрат_тест(таблиця)$statistic
  n <- sum(таблиця)
  r <- nrow(таблиця)
  k <- ncol(таблиця)
  
  sqrt(хи2 / (n * min(r - 1, k - 1)))
}

розпізнати_дату <- function(x) {
  if (inherits(x, "Date")) {
    return(x)
  }
  
  дата <- suppressWarnings(
    parse_date_time(
      as.character(x),
      orders = c("dmy", "ymd", "mdy", "dmy HMS", "ymd HMS", "mdy HMS")
    )
  )
  
  as.Date(дата)
}

#Форматування p-value
формат_p <- function(p) {
  ifelse(p < 0.001, "<0.001", as.character(round(p, 3)))
}

#Форматування відсотків
формат_відсотка <- function(x, digits = 1) {
  paste0(round(x, digits), "%")
}

#Форматування довірчого інтервалу
формат_ді <- function(lower, upper, digits = 1, suffix = "") {
  paste0(
    "[",
    round(lower, digits),
    "; ",
    round(upper, digits),
    "]",
    suffix
  )
}

