  `Легкі ДТП` = c(легкі_день, легкі_темрява_без_освітлення),
  `Тяжкі ДТП` = c(тяжкі_день, тяжкі_темрява_без_освітлення),
  `% тяжких` = c(
    формат_відсотка(p_день * 100, 1),
    формат_відсотка(p_темрява_без_освітлення * 100, 1)
  )
)

