зробити_html_таблицю <- function(data) {
  назви <- names(data)
  
  tags$table(
    style = "
      border-collapse: collapse;
      font-family: Arial, sans-serif;
      font-size: 15px;
      margin-bottom: 30px;
      min-width: 720px;
    ",
    
    tags$thead(
      tags$tr(
        lapply(
          назви,
          function(h) {
            tags$th(
              h,
              style = "
                border-bottom: 2px solid #BDBDBD;
                padding: 8px 12px;
                text-align: left;
                font-weight: 700;
                background-color: #F4F6F7;
              "
            )
          }
        )
      )
    ),
    
    tags$tbody(
      lapply(
        seq_len(nrow(data)),
        function(i) {
          tags$tr(
            lapply(
              seq_along(data),
              function(j) {
                tags$td(
                  as.character(data[[j]][i]),
                  style = "
                    border-bottom: 1px solid #E0E0E0;
                    padding: 8px 12px;
                    text-align: left;
                  "
                )
              }
            )
          )
