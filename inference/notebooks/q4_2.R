# 6. Частина B. Planned contrast:
# Темрява без освітлення vs денне світло
дані_контрасту <- дані_чисті %>%
  filter(умови_освітлення %in% c(
    "Денне світло",
    "Темрява, освітлення відсутнє"
  )) %>%
  group_by(умови_освітлення) %>%
  summarise(
    n = n(),
    легкі_ДТП = sum(severe == 0),
    тяжкі_ДТП = sum(severe == 1),
    p_hat = тяжкі_ДТП / n,
    .groups = "drop"
  )

if (!all(c("Денне світло", "Темрява, освітлення відсутнє") %in% дані_контрасту$умови_освітлення)) {
  stop("У даних немає категорії 'Денне світло' або 'Темрява, освітлення відсутнє'.")
}

p_день <- дані_контрасту %>%
  filter(умови_освітлення == "Денне світло") %>%
  pull(p_hat)

n_день <- дані_контрасту %>%
  filter(умови_освітлення == "Денне світло") %>%
  pull(n)

легкі_день <- дані_контрасту %>%
  filter(умови_освітлення == "Денне світло") %>%
  pull(легкі_ДТП)

тяжкі_день <- дані_контрасту %>%
  filter(умови_освітлення == "Денне світло") %>%
  pull(тяжкі_ДТП)

p_темрява_без_освітлення <- дані_контрасту %>%
  filter(умови_освітлення == "Темрява, освітлення відсутнє") %>%
  pull(p_hat)

n_темрява_без_освітлення <- дані_контрасту %>%
  filter(умови_освітлення == "Темрява, освітлення відсутнє") %>%
  pull(n)

легкі_темрява_без_освітлення <- дані_контрасту %>%
  filter(умови_освітлення == "Темрява, освітлення відсутнє") %>%
  pull(легкі_ДТП)

тяжкі_темрява_без_освітлення <- дані_контрасту %>%
  filter(умови_освітлення == "Темрява, освітлення відсутнє") %>%
  pull(тяжкі_ДТП)

різниця_часток <- p_темрява_без_освітлення - p_день

se_різниці <- sqrt(
  p_темрява_без_освітлення * (1 - p_темрява_без_освітлення) / n_темрява_без_освітлення +
    p_день * (1 - p_день) / n_день
)

z_контраст <- різниця_часток / se_різниці

#H0: p_темрява_без_освітлення <= p_день
#H1: p_темрява_без_освітлення > p_день
p_контраст <- pnorm(z_контраст, lower.tail = FALSE)

z_crit <- qnorm(0.975)

ci_контраст_lower <- різниця_часток - z_crit * se_різниці
ci_контраст_upper <- різниця_часток + z_crit * se_різниці

